    input wire D,           // ?????? ????
    input wire [2:0] sel,   // 3 ??????? ????? (A2, A1, A0)
    output wire [7:0] Y     // ?????? Y0?Y7
);

    wire nA0, nA1, nA2;

    // ???????? ???????? ??????
    not (nA0, sel[0]);
    not (nA1, sel[1]);
    not (nA2, sel[2]);

    // ???????? ??????? ????? AND (D & ?????????? ?????)
    and (Y[0], D, nA2, nA1, nA0);  // 000
    and (Y[1], D, nA2, nA1,  sel[0]);  // 001
    and (Y[2], D, nA2,  sel[1], nA0);  // 010
    and (Y[3], D, nA2,  sel[1],  sel[0]);  // 011
    and (Y[4], D,  sel[2], nA1, nA0);  // 100
    and (Y[5], D,  sel[2], nA1,  sel[0]);  // 101
    and (Y[6], D,  sel[2],  sel[1], nA0);  // 110
    and (Y[7], D,  sel[2],  sel[1],  sel[0]);  // 111

endmodule

